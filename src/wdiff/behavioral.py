"""Behavioral diff: run the same probe prompts through both models, compare outputs.

Each probe set (probes/<set>.jsonl: id, prompt, optional answer) is generated by BASE and
EDITED with identical settings and the same RNG seed. Per model and set we report:

    hit_cap_rate  = fraction that reached max_new_tokens without an end-of-turn token
    repeat_rate   = fraction where some 20-token window occurs ≥ 3 times
    loop_rate     = fraction with repeat OR hit_cap (both parts reported above)
    answer_rate   = fraction with a final \\boxed{…}               (math sets only)
    accuracy      = fraction whose last \\boxed{…} number == reference (math sets only)
    refusal_rate  = fraction whose response contains a refusal phrase
    short_rate    = fraction whose response is empty or < 20 tokens
    mean_tokens   = mean generated length

"Response" is the text after </think> for a thinking model (thinking is turned on when the
chat template supports it); for a model without thinking it is the whole generation. A
thinking generation that never closes its thinking has no response: it counts as not
refusing and as short, and no_response_rate says how often that happened.

Presence penalty (Qwen's card and the paper use 1.5): HF generate has none, so a
logits processor subtracts 1.5 from every token already present in the generated
output (not the prompt), the vLLM/OpenAI definition.
"""

from __future__ import annotations

import json
import re
import time
from collections import Counter
from collections.abc import Callable
from pathlib import Path

import torch

SETTINGS = {"temperature": 0.6, "top_p": 0.95, "top_k": 20, "presence_penalty": 1.5}
WINDOW, REPEATS, SHORT = 20, 3, 20
REFUSAL_PHRASES = [
    "i can't", "i cannot", "i'm not able to", "i am not able to", "i'm unable", "i am unable",
    "i won't", "i will not", "i'm sorry", "i am sorry", "i apologize", "as an ai",
    "can't help with", "cannot help with", "can't assist", "cannot assist", "not able to help",
]  # fmt: skip


# ---------- metrics (pure functions, unit-tested) ----------


def has_repeat(tokens: list[int], window: int = WINDOW, repeats: int = REPEATS) -> bool:
    counts = Counter(tuple(tokens[i : i + window]) for i in range(len(tokens) - window + 1))
    return any(c >= repeats for c in counts.values())


def last_boxed(text: str) -> str | None:
    """Content of the last \\boxed{...}, matching nested braces."""
    start = text.rfind("\\boxed{")
    if start < 0:
        return None
    i, depth = start + len("\\boxed{"), 1
    for j in range(i, len(text)):
        depth += {"{": 1, "}": -1}.get(text[j], 0)
        if depth == 0:
            return text[i:j]
    return None


def to_number(s: str | None) -> float | None:
    if s is None:
        return None
    nums = re.findall(r"-?\d+(?:\.\d+)?", s.replace(",", ""))
    return float(nums[-1]) if nums else None


def response_of(text: str, thinking: bool = True) -> str | None:
    if not thinking:
        return text.strip()
    return text.split("</think>", 1)[1].strip() if "</think>" in text else None


def is_refusal(response: str | None) -> bool:
    r = (response or "").lower().replace("’", "'")
    return any(p in r for p in REFUSAL_PHRASES)


def score(gen: dict, answer: str | None, tok_len: Callable[[str], int]) -> dict:
    resp = response_of(gen["text"], gen.get("thinking", True))
    out = {
        "hit_cap": gen["hit_cap"],
        "repeat": has_repeat(gen["tokens"]),
        "no_response": resp is None,
        "refusal": is_refusal(resp),
        "short": resp is None or tok_len(resp) < SHORT,
        "n_tokens": len(gen["tokens"]),
    }
    out["loop"] = out["hit_cap"] or out["repeat"]
    if answer is not None:
        boxed = last_boxed(resp or "")
        out["answered"] = boxed is not None
        pred, ref = to_number(boxed), to_number(answer)
        out["correct"] = pred is not None and ref is not None and abs(pred - ref) < 1e-6
    return out


def aggregate(scores: list[dict]) -> dict:
    n = len(scores)
    rate = lambda k: sum(s[k] for s in scores) / n
    m = {
        "n": n,
        "hit_cap_rate": rate("hit_cap"),
        "repeat_rate": rate("repeat"),
        "loop_rate": rate("loop"),
        "no_response_rate": rate("no_response"),
        "refusal_rate": rate("refusal"),
        "short_rate": rate("short"),
        "mean_tokens": sum(s["n_tokens"] for s in scores) / n,
    }
    if "answered" in scores[0]:
        m["answer_rate"], m["accuracy"] = rate("answered"), rate("correct")
    return m


# ---------- generation ----------


def load_probes(directory: Path, max_prompts: int) -> dict[str, list[dict]]:
    sets = {}
    for f in sorted(directory.glob("*.jsonl")):
        rows = [json.loads(line) for line in f.read_text().splitlines() if line.strip()]
        sets[f.stem] = rows[:max_prompts]
    return dict(sorted(sets.items(), key=lambda kv: "answer" not in kv[1][0]))  # math first


def pick_device(name: str) -> str:
    if name != "auto":
        return name
    if torch.cuda.is_available():
        return "cuda"
    return "mps" if torch.backends.mps.is_available() else "cpu"


def _presence_processor(prompt_len: int, penalty: float):
    from transformers import LogitsProcessor

    class Presence(LogitsProcessor):
        def __call__(self, input_ids, scores):
            gen = input_ids[:, prompt_len:]
            if gen.shape[1]:
                seen = torch.zeros_like(scores, dtype=torch.bool).scatter_(1, gen, True)
                scores = scores - penalty * seen.to(scores.dtype)
            return scores

    return Presence()


class Runner:
    """One model loaded on one device; generates batches with the fixed settings."""

    def __init__(self, path: Path, device: str):
        from transformers import AutoModelForCausalLM, AutoTokenizer

        self.device = device
        self.tok = AutoTokenizer.from_pretrained(path, padding_side="left")
        dtype = torch.float32 if device == "cpu" else torch.bfloat16
        self.model = AutoModelForCausalLM.from_pretrained(path, dtype=dtype).to(device).eval()
        if self.tok.pad_token is None:  # Llama ships without one; left padding is masked anyway
            self.tok.pad_token = self.tok.eos_token
        gen_eos = self.model.generation_config.eos_token_id
        self.end_ids = {self.tok.eos_token_id, *(gen_eos if isinstance(gen_eos, list) else [gen_eos])}
        if "<|im_end|>" in self.tok.get_vocab():
            self.end_ids.add(self.tok.convert_tokens_to_ids("<|im_end|>"))
        self.end_ids.discard(None)
        self.thinking = "enable_thinking" in (self.tok.chat_template or "")

    def tok_len(self, text: str) -> int:
        return len(self.tok(text, add_special_tokens=False).input_ids)

    @torch.no_grad()
    def generate(self, prompts: list[str], max_new_tokens: int) -> list[dict]:
        texts = [
            self.tok.apply_chat_template(
                [{"role": "user", "content": p}],
                tokenize=False,
                add_generation_prompt=True,
                enable_thinking=True,  # Qwen3.5's template defaults to thinking OFF; others ignore it
            )
            for p in prompts
        ]
        enc = self.tok(texts, return_tensors="pt", padding=True).to(self.device)
        plen = enc.input_ids.shape[1]
        out = self.model.generate(
            **enc,
            do_sample=True,
            temperature=SETTINGS["temperature"],
            top_p=SETTINGS["top_p"],
            top_k=SETTINGS["top_k"],
            max_new_tokens=max_new_tokens,
            logits_processor=[_presence_processor(plen, SETTINGS["presence_penalty"])],
            pad_token_id=self.tok.pad_token_id,
        )
        gens = []
        for row in out[:, plen:].tolist():
            end = next((i for i, t in enumerate(row) if t in self.end_ids), None)
            tokens = row if end is None else row[:end]
            gens.append({
                "text": self.tok.decode(tokens, skip_special_tokens=False),
                "tokens": tokens,
                "hit_cap": end is None,
                "thinking": self.thinking,
            })  # fmt: skip
        return gens

    def close(self) -> None:
        del self.model
        if self.device == "cuda":
            torch.cuda.empty_cache()
        elif self.device == "mps":
            torch.mps.empty_cache()


class BudgetExceeded(RuntimeError):
    pass


def run_model(
    runner: Runner,
    probes: dict[str, list[dict]],
    max_new_tokens: int,
    batch_size: int,
    seed: int,
    budget_s: float | None,
    total_gens: int,
    log: Callable[[str], None] = print,
) -> dict[str, list[dict]]:
    """Generate every probe; after the first batch, project the whole run's time."""
    torch.manual_seed(seed)
    results: dict[str, list[dict]] = {}
    t0, done, checked = time.monotonic(), 0, False
    for name, rows in probes.items():
        results[name] = []
        for i in range(0, len(rows), batch_size):
            batch = rows[i : i + batch_size]
            results[name] += runner.generate([r["prompt"] for r in batch], max_new_tokens)
            done += len(batch)
            elapsed = time.monotonic() - t0
            if not checked:
                checked = True
                projected = elapsed / done * total_gens
                log(f"first {done} generations took {elapsed:.0f}s; "
                    f"projected total for both models: {projected / 60:.0f} min")  # fmt: skip
                if budget_s is not None and projected > budget_s:
                    raise BudgetExceeded(
                        f"projected {projected / 60:.0f} min > {budget_s / 60:.0f} min budget; "
                        "use a GPU, lower --max-new-tokens / --max-prompts, or pass --force"
                    )
            log(f"  {name}: {len(results[name])}/{len(rows)} ({elapsed / 60:.1f} min)")
    return results
